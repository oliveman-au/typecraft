export function getRandomSentence(excludeIndex?: number): { text: string; index: number } {
  let index: number
  do {
    index = Math.floor(Math.random() * sentences.length)
  } while (index === excludeIndex && sentences.length > 1)
  return { text: sentences[index], index }
}

export function buildInfiniteWordList(): string[] {
  const shuffled = [...sentences].sort(() => Math.random() - 0.5)
  return shuffled.flatMap(s => s.split(' '))
}

export function buildWordList(count: number = 200): string[] {
  const allWords = buildInfiniteWordList()
  const start = Math.floor(Math.random() * Math.max(1, allWords.length - count))
  return allWords.slice(start, start + count)
}
